    def _update_or_create_budget(self, user, category, amount, threshold=80):
        budget = Budget.objects.filter(
            user=user,
            category=category,
            month=5,
            year=2026,
            period="monthly",
        ).first()
        if budget:
            budget.amount = Decimal(str(amount))
            budget.alert_threshold = Decimal(str(threshold))
            budget.save()
            return budget
        return Budget.objects.create(
            user=user,
            category=category,
            amount=Decimal(str(amount)),
            period="monthly",
            month=5,
            year=2026,
            alert_threshold=Decimal(str(threshold)),
        )

