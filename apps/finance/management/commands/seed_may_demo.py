    def _create_tx(self, user, tx_type, amount, account, category, notes, occurred_at, destination_account=None):
        amount = Decimal(str(amount))
        tx = Transaction(
            user=user,
            type=tx_type,
            amount=amount,
            account=account,
            destination_account=destination_account if tx_type == "transfer" else None,
            category=category if tx_type != "transfer" else None,
            notes=f"{DEMO_PREFIX} {notes}",
            occurred_at=occurred_at,
        )
        tx.full_clean()
        tx.save()

        if tx_type == "income":
            account.balance += amount
            account.save(update_fields=["balance"])
        elif tx_type == "expense":
            account.balance -= amount
            account.save(update_fields=["balance"])
        elif tx_type == "transfer" and destination_account:
            account.balance -= amount
            destination_account.balance += amount
            account.save(update_fields=["balance"])
            destination_account.save(update_fields=["balance"])

        return tx

