DEMO_PREFIX = "May 2026 Demo:"


class Command(BaseCommand):
    help = "Seed a diverse May 2026 demo dataset for the Personal Finance project."

    def add_arguments(self, parser):
        parser.add_argument(
            "--username",
            default="taikhoantest",
            help="Username to seed data for. Default: taikhoantest",
        )
        parser.add_argument(
            "--reset",
            action="store_true",
            help="Remove previously generated May 2026 demo records before inserting new ones.",
        )

    def handle(self, *args, **options):
        username = options["username"]
        reset = options["reset"]
        User = get_user_model()

        user = User.objects.filter(username=username).first()
        if not user:
            user = User.objects.create_user(
                username=username,
                email=f"{username}@example.com",
                password="12345678",
            )
            self.stdout.write(self.style.WARNING(
                f"User '{username}' did not exist, so it was created with password '12345678'."
            ))

        with db_transaction.atomic():
            if reset:
                self._reset_previous_demo(user)

            accounts = self._seed_accounts(user)
            categories = self._seed_categories(user)
            self._seed_budgets(user, categories)
            self._seed_goals(user)
            self._seed_recurring(user, accounts, categories)
            created_transactions = self._seed_transactions(user, accounts, categories)

        self.stdout.write(self.style.SUCCESS("May 2026 demo data has been seeded successfully."))
        self.stdout.write(f"User: {username}")
        self.stdout.write(f"Transactions created: {created_transactions}")
        self.stdout.write("Open Dashboard again and hard refresh with Ctrl + F5.")

    def _aware(self, year: int, month: int, day: int, hour: int = 9, minute: int = 0):
        return timezone.make_aware(
            datetime(year, month, day, hour, minute),
            timezone.get_current_timezone(),
        )

    def _reset_previous_demo(self, user):
        """Reverse balance effects and remove previous demo records generated by this command."""
        demo_transactions = list(
            Transaction.objects.filter(user=user, notes__startswith=DEMO_PREFIX)
            .select_related("account", "destination_account")
            .order_by("-occurred_at", "-id")
        )

        for tx in demo_transactions:
            if tx.type == "income":
                tx.account.balance -= tx.amount
                tx.account.save(update_fields=["balance"])
            elif tx.type == "expense":
                tx.account.balance += tx.amount
                tx.account.save(update_fields=["balance"])
            elif tx.type == "transfer" and tx.destination_account:
                tx.account.balance += tx.amount
                tx.destination_account.balance -= tx.amount
                tx.account.save(update_fields=["balance"])
                tx.destination_account.save(update_fields=["balance"])
            tx.delete()

        RecurringTransaction.objects.filter(user=user, notes__startswith=DEMO_PREFIX).delete()
        FinancialGoal.objects.filter(user=user, notes__startswith=DEMO_PREFIX).delete()
        Budget.objects.filter(user=user, month=5, year=2026).delete()

    def _get_or_create_account(self, user, name, acc_type, bank_name, initial_balance):
        account, created = Account.objects.get_or_create(
            user=user,
            name=name,
            defaults={
                "type": acc_type,
                "bank_name": bank_name,
                "currency": "VND",
                "initial_balance": Decimal(str(initial_balance)),
                "balance": Decimal(str(initial_balance)),
                "is_active": True,
            },
        )
        if not created:
            changed = False
            if not account.is_active:
                account.is_active = True
                changed = True
            if account.type != acc_type:
                account.type = acc_type
                changed = True
            if bank_name and account.bank_name != bank_name:
                account.bank_name = bank_name
                changed = True
            if changed:
                account.save()
        return account

