    def _get_or_create_category(self, user, name, cat_type, parent=None):
        category = Category.objects.filter(
            user=user,
            name=name,
            type=cat_type,
            parent=parent,
        ).first()
        if category:
            if not category.is_active:
                category.is_active = True
                category.save(update_fields=["is_active"])
            return category
        return Category.objects.create(
            user=user,
            name=name,
            type=cat_type,
            parent=parent,
            is_active=True,
        )

